function translateNote(note: string, locale: Locale) {
  if (locale !== "es") return note;
  return note
    .replaceAll("Monday – Thursday", "Lunes a jueves")
    .replaceAll("Friday", "Viernes")
    .replaceAll("Saturday", "Sábado")
    .replaceAll("Sunday", "Domingo")
    .replaceAll("Ford service", "Servicio Ford")
    .replaceAll("Lincoln service", "Servicio Lincoln")
    .replaceAll("Parts", "Partes");
}

export function translateNav(items: NavItem[], locale: Locale): NavItem[] {
  if (locale === "en") return items;
  return items.map((item) => ({
    ...item,
    label: item.id === "espanol" ? "English" : (navEs[item.label] ?? item.label),
    href: item.id === "espanol" ? "/english" : item.href,
    columns: item.columns?.map((column) => ({
      ...column,
      heading: navEs[column.heading] ?? column.heading,
      note: column.note ? translateNote(column.note, locale) : column.note,
      links: column.links.map((link) => ({
        ...link,
        label: navEs[link.label] ?? link.label,
      })),
    })),
  }));
}

