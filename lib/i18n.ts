export const LOCALE_COOKIE = "prmf_locale";
export type Locale = "en" | "es";

export function isLocale(value: string | undefined): value is Locale {
  return value === "en" || value === "es";
}

export function safeNextPath(next: string | null | undefined) {
  if (!next || !next.startsWith("/") || next.startsWith("//") || next.includes("://")) return "/";
  if (next === "/espanol" || next === "/english" || next.startsWith("/espanol?") || next.startsWith("/english?")) {
    return "/";
  }
  return next;
}

const hourDaysEn: Record<string, string> = {
  "Monday – Thursday": "Mon–Thu",
  Friday: "Fri",
  Saturday: "Sat",
  Sunday: "Sun",
};

const hourDaysEs: Record<string, string> = {
  "Monday – Thursday": "Lun–Jue",
  Friday: "Vie",
  Saturday: "Sáb",
  Sunday: "Dom",
};

export function compactHourDays(days: string, locale: Locale) {
  const map = locale === "es" ? hourDaysEs : hourDaysEn;
  return map[days] ?? days;
}

export function formatHourTime(time: string) {
  return time.replaceAll(":00", "");
}

